// Turns lib/parse.js + lib/capture.js into the text of the "Scan SGCarMart" bookmark.
// A bookmark cannot load modules, so the two files are joined into one self-contained script.

function strip(source) {
  return source
    .replace(/^import .*$/gm, '')                    // module wiring is not needed once the files are joined
    .replace(/^export \{[^}]*\};?$/gm, '')
    .replace(/^export\s+/gm, '')
    .split('\n').filter((line) => !/^\s*(\/\/|\/\*\*|\*\/|\*(\s|$))/.test(line) && line.trim()).join('\n');   // whole-line comments and blanks
}

/** The script the bookmark runs. dashUrl is the dashboard's own address (no # part). */
export function bookmarkletCode(parseSource, captureSource, dashUrl) {
  return `void (async () => {\n${strip(parseSource)}\n${strip(captureSource)}\nawait runCapture(window, ${JSON.stringify(dashUrl)});\n})()` +
    `.catch((e) => { alert('SG Car Deals could not read this page: ' + (e && e.message ? e.message : e)); });`;
}

export function bookmarkletHref(parseSource, captureSource, dashUrl) {
  return 'javascript:' + encodeURIComponent(bookmarkletCode(parseSource, captureSource, dashUrl));
}

/**
 * The same reader as a browser-extension content script. A site's security policy can stop a
 * bookmark from running; it cannot stop an extension you installed yourself.
 * It shows a "Scan for SG Car Deals" button on SGCarMart used-car search pages.
 */
export function extensionCode(parseSource, captureSource, dashUrl) {
  return `// Generated by scripts/build-extension.mjs from lib/parse.js and lib/capture.js. Do not edit by hand.
(() => {
const DASHBOARD = ${JSON.stringify(dashUrl)};
${strip(parseSource)}
${strip(captureSource)}
const onSearch = () => location.hostname === 'www.sgcarmart.com' && location.pathname.startsWith('/used-cars/listing');
function launcher() {
  const busy = document.getElementById('scd-capture');
  let b = document.getElementById('scd-launch');
  if (!onSearch() || busy) { if (b) b.remove(); return; }
  if (b) return;
  b = document.createElement('button');
  b.id = 'scd-launch'; b.type = 'button'; b.textContent = 'Scan for SG Car Deals';
  b.style.cssText = 'position:fixed;right:16px;bottom:16px;z-index:2147483647;background:#0b5d4f;color:#fff;border:2px solid #fff;' +
    'font:600 15px/1.2 system-ui,sans-serif;padding:12px 16px;border-radius:999px;cursor:pointer;box-shadow:0 6px 24px rgba(0,0,0,.35)';
  b.addEventListener('click', () => {
    b.remove();
    runCapture(window, DASHBOARD).catch((e) => { alert('SG Car Deals could not read this page: ' + (e && e.message ? e.message : e)); });
  });
  document.body.appendChild(b);
}
launcher();
setInterval(launcher, 1000);       // the site changes pages without reloading, so keep checking where we are
})();
`;
}
